#include <stdio.h>

int main() {
    unsigned int n;

    if (scanf_s("%u", &n) != 1) {
        return 1;
    }

    // Както коментирахме на упражненията, всяка степен на двойката в двоичен запис
    // е единица, последвана от нули (например 8 = 1000).
    // Изваждането на 1 обръща тази единица и всички нули след нея (7 = 0111),
    // затова n и n - 1 нямат общ бит 1 и n & (n - 1) дава 0.
    // Проверката n != 0 е нужна, защото за 0 изразът също дава 0,
    // а 0 не е степен на двойката.
    if (n != 0 && (n & (n - 1)) == 0) {
        printf("Power of two\n");
    } else {
        printf("Not a power of two\n");
    }

    return 0;
}
